"""Regenerate the file "near_zero_test_cases.rs" with `uv run scripts/generate_near_zero_answers.py`.

Inputs are binary64/binary32 values, converted exactly to mpmath, and evaluated to give the expected answer.
The evaluation is done at 100 and 180 decimal digits, and it is asserted that they round to the same float.
"""

import math
import struct
import os

import mpmath as mp


def f32(x: float):
    """Truncates a float value to 32-bits in the same way that C does and returns the resulting value"""
    return struct.unpack("f", struct.pack("f", x))[0]

def f64(x: float):
    """Does the same as `f32` but for a 64-bit float"""
    return struct.unpack("d", struct.pack("d", x))[0]

def print_test_data(cast, cutoff: float, tiny: float, normal: float, neighbors, name: str, rust_type: str, output):
    values = [tiny, 2 * tiny, normal - tiny, normal, *neighbors]
    values += [cast(10.0**e) for e in [-300, -100, -30, -20, -12, -8, -6, -4, -3, -2]]
    values += [cast(i / 1000) for i in range(1, int(cutoff*1000), 3)]
    set = {sign * v for v in values if v != 0 for sign in [-1, 1]}
    output.write(f"/// z-values near zero and W_0(z) for values of type {rust_type}.\n")
    output.write(f"pub static {name}: [({rust_type}, {rust_type}); {len(set)}] = [\n")
    for x in sorted(set):
        with mp.workdps(100):
            expected = cast(mp.lambertw(mp.mpf(x)))
        with mp.workdps(180):
            assert expected == cast(mp.lambertw(mp.mpf(x)))
        output.write(f"    ({repr(x)}, {repr(expected)}),\n")
    output.write("];\n")

THRESHOLD: float = 0.0675
OUTPUT_FILE_NAME: str = "tests/near_zero_test_cases.rs"

tiny = float.fromhex("0x0.0000000000001p-1022")
normal = float.fromhex("0x1p-1022")
cutoff = f64(THRESHOLD)
neighbors = [math.nextafter(cutoff, 0), cutoff, math.nextafter(cutoff, math.inf)]
with open(OUTPUT_FILE_NAME, "w") as file:
    file.write(f"//! Generated by the script in \"scripts/{os.path.basename(__file__)}\".\n\n")
    print_test_data(f64, cutoff, tiny, normal, neighbors, "W0_NEAR_ZERO_ANSWERS", "f64", file)
    file.write("\n")


tiny = 2.0**-149
normal = 2.0**-126
cutoff = f32(THRESHOLD)
bits = struct.unpack("I", struct.pack("f", cutoff))[0]
neighbors = [struct.unpack("f", struct.pack("I", bits + i))[0] for i in [-2, -1, 0, 1, 2]]
with open(OUTPUT_FILE_NAME, "a") as file:
    print_test_data(f32, cutoff, tiny, normal, neighbors, "W0F_NEAR_ZERO_ANSWERS", "f32", file)
