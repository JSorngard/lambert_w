import math
import os
import struct

import numpy as np
import mpmath as mp

def f32(x: float) -> float:
    """Truncates a float value to 32-bits in the same way that C does and returns the resulting value"""
    return struct.unpack("f", struct.pack("f", x))[0]

def f64(x: float) -> float:
    """Does the same as `f32` but for a 64-bit float"""
    return struct.unpack("d", struct.pack("d", x))[0]

def f32_next_down(x: float) -> float:
    bits = struct.unpack("I", struct.pack("f", x))[0]
    return struct.unpack("f", struct.pack("I", bits - 1))[0]

def f32_next_up(x: float) -> float:
    bits = struct.unpack("I", struct.pack("f", x))[0]
    return struct.unpack("f", struct.pack("I", bits + 1))[0]

def f64_next_down(x: float) -> float:
    return math.nextafter(x, 0)

def f64_next_up(x: float) -> float:
    return math.nextafter(x, math.inf)

def print_test_cases(critical_z_values: list[float], cast, next_down, next_up, name: str, rust_type: str, output):
    z_values = []
    for lower_value, upper_value in zip(critical_z_values, critical_z_values[1:] + [math.inf], strict = True):
        z_values += [cast(lower_value), cast(next_up(lower_value)), cast(next_down(upper_value))]
        z_values += map(cast, (np.random.rand(1_000)*(upper_value - lower_value) + lower_value).tolist())
    z_set = sorted({z for z in z_values if z != 0 and z != math.inf})
    output.write("/// z-values and the corresponding values of W0(z) evaluated with mpmath in python.\n")
    output.write(f"pub const {name}: [({rust_type}, {rust_type}); {len(z_set)}] = [\n")
    for x in z_set:
        if x == -1/np.e:
            expected = -1.0
        else:
            with mp.workdps(100):
                expected = cast(mp.lambertw(mp.mpf(x)))
            with mp.workdps(180):
                assert expected == cast(mp.lambertw(mp.mpf(x)))
        output.write(f"    ({repr(x)}, {repr(expected)}),\n")
    output.write("];\n")

